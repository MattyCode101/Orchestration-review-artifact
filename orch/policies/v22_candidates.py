"""Template v2.2, switch C: candidate options (new file).

The harness lists 2 to 4 candidate next calls, generated by general rules that name no worker and scale to any number of
workers. The rules reuse the goal-repair v2 logic of orch/policies/repair_loop.py (RepairLoopPolicy with the v2
parameters g05: repair_attempts 1, repair_preserve_placement false, gentle_step on):

  push    the goal's worker (the card whose objective is the brief's goal), from the best state within limits,
          placement may change, 2 attempts (the bold step)
  repair  for each broken limit: the worker whose objective is that limit's metric, from the best limit-breaking state
          that has a goal gain over the best state within limits (on equal goal values the state whose limit is broken
          by less), placement may change, 1 attempt (the repair step)
  gentle  the goal's worker, from the best state within limits, placement kept, 1 attempt (the gentle step)

As in goal-repair v2, none of the three asks the worker to select inside the limits (no guards, "respect limits: no"); the
candidate line says so. A combination the view already shows as out of options is not offered. With fewer than two
candidates left, the push and the gentle move from the start are added when they differ. Attempts never exceed the
remaining budget.

Candidates carry neutral labels (Option A, B, ...) assigned after a seeded shuffle of the order, so the label and the
position say nothing about the rule behind the call. The shuffle seed is a hash of (seed, episode id, decision index): the
same decision always renders the same list. Each candidate shows the experience line of its worker and placement setting
(the same line the experience section shows, or "no line" when fewer than four designs support it).
"""
from __future__ import annotations

import hashlib
import random
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, replace

from orch.contract.models import BriefTerm, MetricName, WorkerCard
from orch.contract.views import PolicyView, StateSummary
from orch.policies.llm_view import METRIC_NAMES, effective_bands
from orch.policies.v2_policy import exhausted_combinations
from orch.policies.v2_view import unique_states
from orch.policies.v2_vocab import PLACEMENT_V2
from orch.policies.v22_view import aliases_of, attempts_phrase, state_summary_line

GOAL_REPAIR_V2 = {"repair_attempts": 1, "repair_preserve_placement": False, "gentle_step": True}
BOLD_ATTEMPTS = 2
GENTLE_ATTEMPTS = 1
MAX_CANDIDATES = 4
MIN_CANDIDATES = 2


@dataclass(frozen=True)
class Candidate:
    kind: str                      # push | repair | gentle (never shown to the model)
    worker_id: str
    base_state_id: str
    base_alias: str
    preserve_placement: bool
    attempts: int
    respect: bool = False          # goal-repair v2 asks for no guards
    limit_metric: str | None = None
    label: str = ""

    def key(self) -> tuple[str, str, bool]:
        return (self.worker_id, self.base_state_id, self.preserve_placement)

    def as_record(self) -> dict[str, object]:
        return {"label": self.label, "kind": self.kind, "worker": self.worker_id, "base": self.base_alias,
                "placement": PLACEMENT_V2[self.preserve_placement], "attempts": self.attempts, "respect": self.respect,
                "limit_metric": self.limit_metric}


def _goal_value(view: PolicyView, state: StateSummary) -> float | None:
    return state.metrics.get(view.brief.objective.metric)


def _improves(view: PolicyView, candidate: StateSummary, reference: StateSummary) -> bool:
    a, b = _goal_value(view, candidate), _goal_value(view, reference)
    if a is None or b is None:
        return False
    return a > b if view.brief.objective.direction == "max" else a < b


def _violates(view: PolicyView, state: StateSummary, term: BriefTerm) -> bool:
    ref, value = view.start.metrics.get(term.metric), state.metrics.get(term.metric)
    if ref is None or value is None:
        return False
    limit = term.factor * ref + term.offset
    return not (value <= limit if term.comparison == "<=" else value >= limit)


def _break_depth(view: PolicyView, state: StateSummary, term: BriefTerm) -> float:
    """How far a state is outside one limit, in the metric's units (positive when the limit is broken)."""

    ref, value = view.start.metrics.get(term.metric), state.metrics.get(term.metric)
    if ref is None or value is None:
        return 0.0
    limit = term.factor * ref + term.offset
    return (value - limit) if term.comparison == "<=" else (limit - value)


def _card_for(view: PolicyView, metric: MetricName, exclude: WorkerCard) -> WorkerCard | None:
    matches = [c for c in view.worker_cards if c.objective.metric == metric and c.id != exclude.id]
    return matches[0] if len(matches) == 1 else None


def generate_candidates(view: PolicyView, *, params: Mapping[str, object] = GOAL_REPAIR_V2) -> list[Candidate]:
    """The candidate calls of one decision, in rule order (push, repairs, gentle); labels are not set yet."""

    if view.budget_left <= 0:
        return []
    goal = view.brief.objective.metric
    primaries = [c for c in view.worker_cards if c.objective.metric == goal]
    if len(primaries) != 1:
        return []
    primary = primaries[0]
    aliases = aliases_of(view)
    best = view.best_valid if view.best_valid is not None else view.start
    spent = exhausted_combinations(view)
    budget = view.budget_left
    out: list[Candidate] = []

    def add(kind: str, card: WorkerCard, base: StateSummary, preserve: bool, attempts: int, limit: str | None = None) -> None:
        if (card.id, base.state_id, preserve) in spent or any(c.key() == (card.id, base.state_id, preserve) for c in out):
            return
        out.append(Candidate(kind, card.id, base.state_id, aliases[base.state_id], preserve, max(1, min(attempts, budget)),
                             False, limit))

    add("push", primary, best, False, BOLD_ATTEMPTS)
    states = unique_states(view)
    for term in view.brief.terms:
        pool = [s for s in states if s.physically_valid and not s.brief_valid and _violates(view, s, term)
                and _improves(view, s, best)]
        card = _card_for(view, term.metric, primary)
        if not pool or card is None:
            continue
        maximise = view.brief.objective.direction == "max"
        # the best goal value; on a tie the state whose limit is broken by less (decision of 2026-11-13, item 4)
        base = max(pool, key=lambda s: ((_goal_value(view, s) or 0.0) * (1.0 if maximise else -1.0),
                                        -_break_depth(view, s, term)))
        add("repair", card, base, bool(params["repair_preserve_placement"]), int(params["repair_attempts"]),
            term.metric.value)
    if params.get("gentle_step", True):
        add("gentle", primary, best, True, GENTLE_ATTEMPTS)
    if len(out) < MIN_CANDIDATES and best.state_id != view.start.state_id:
        add("push", primary, view.start, False, BOLD_ATTEMPTS)
    if len(out) < MIN_CANDIDATES:
        add("gentle", primary, view.start, True, GENTLE_ATTEMPTS)
    return out[:MAX_CANDIDATES]


def shuffled(cands: Sequence[Candidate], *, seed: int, episode_id: str, decision_index: int) -> list[Candidate]:
    """Neutral labels after a seeded shuffle: the same (seed, episode, decision) always gives the same list."""

    digest = hashlib.sha256(f"{seed}|{episode_id}|{decision_index}".encode("utf-8")).digest()
    rng = random.Random(int.from_bytes(digest[:8], "big"))
    order = list(cands)
    rng.shuffle(order)
    return [replace(c, label=f"Option {chr(ord('A') + i)}") for i, c in enumerate(order)]


def render_candidates(cands: Sequence[Candidate], view: PolicyView, *, header: str, intro: str, no_line: str,
                      line_for: Callable[[str, bool], str | None] | None) -> str:
    """Section text; `line_for(worker, preserve_placement)` returns the experience line (or None); None function: no lines."""

    if not cands:
        return ""
    bands = effective_bands(view.noise_bands, view.start.metrics)
    by_id = {s.state_id: s for s in unique_states(view)}
    lines = [header, intro]
    for c in cands:
        base = by_id[c.base_state_id]
        is_start = c.base_state_id == view.start.state_id
        facts = state_summary_line(view, base, bands)
        if is_start:
            facts = "the start; " + facts
        lines.append(f"{c.label}: worker {c.worker_id} from {c.base_alias} ({facts}), {PLACEMENT_V2[c.preserve_placement]}, "
                     f"{attempts_phrase(c.attempts)}, respect limits: {'yes' if c.respect else 'no'}.")
        if line_for is not None:
            line = line_for(c.worker_id, c.preserve_placement)
            if line:                      # "placement may change (19 calls from 4 designs): goal ..."
                lines.append(f"  Experience for {c.worker_id}, {line}")
            else:
                lines.append(f"  Experience for {c.worker_id}, {PLACEMENT_V2[c.preserve_placement]}: {no_line}")
    return "\n".join(lines)


def which_candidate(cands: Sequence[Candidate], mandate: Mapping[str, object] | None,
                    aliases: Mapping[str, str]) -> dict[str, object]:
    """Which candidate a parsed mandate equals: {"pick": label | "custom" | "stop", "exact": bool, "kind": ...}."""

    if mandate is None:
        return {"pick": "stop", "exact": False, "kind": None}
    base_id = aliases.get(str(mandate["base"]))
    for c in cands:
        if (c.worker_id, c.base_state_id, c.preserve_placement) == (mandate["worker"], base_id, mandate["preserve"]):
            same = c.attempts == mandate["attempts"] and c.respect == mandate["respect"]
            return {"pick": c.label, "exact": bool(same), "kind": c.kind}
    return {"pick": "custom", "exact": False, "kind": None}


