"""Template v2.2: independent switches on top of the frozen template v2.1 (new file; nothing frozen is edited).

  E   experience lines                                (v2.1: on)
  P   physical description                            (v2.1: on)
  H   history of the saved states: "full" or "compact" (latest values and categories only)   (v2.1: full)
  R   relative context: each metric also against an anchor (new, off in v2.1)
  C   candidate options generated by the harness      (built in revision 1, dropped from every variant on 2026-11-13;
                                                       the code stays, no variant uses it)
  S   two-call sequence experience                    (built in revision 1, replaced by S2; no variant uses it)
  S2  situation experience S': evidence for the situation of the current decision (new, off in v2.1)
  U   unanchored worker choice: the "Push" consideration, which says the goal's own worker usually moves the goal most,
      is replaced by a neutral line (new, off in v2.1; needs experience content in the prompt)

With the defaults (E and P on, H full, R, C, S, S2 and U off) the rendered prompt is the template v2.1 prompt byte for byte
(tests/test_v22_prompt.py). The grid variants V1 to V8 are the registry below; V0 is the round-1 wording F1-R1 and is not a
switch set.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

SCHEMA = "template-v22-variant-v2"
H_MODES = ("full", "compact")
BASE_DEFINITION = "configs/policies/template_v2.1.yaml"
SWITCH_NAMES = ("E", "P", "H", "R", "C", "S", "S2", "U")


@dataclass(frozen=True)
class Switches:
    E: bool = True
    P: bool = True
    H: str = "full"
    R: bool = False
    C: bool = False
    S: bool = False
    S2: bool = False
    U: bool = False

    def __post_init__(self) -> None:
        if self.H not in H_MODES:
            raise ValueError(f"H must be one of {', '.join(H_MODES)}")
        if self.U and not self.experience_shown:
            raise ValueError("U points at what each worker and setting did: it needs experience content (E, S or S2)")

    @property
    def is_v21(self) -> bool:
        return self == Switches()

    @property
    def experience_shown(self) -> bool:
        """Any experience content (single-call lines, two-call patterns or situation lines) is in the prompt."""

        return self.E or self.S or self.S2

    def as_json(self) -> dict[str, Any]:
        return {"E": self.E, "P": self.P, "H": self.H, "R": self.R, "C": self.C, "S": self.S, "S2": self.S2, "U": self.U}

    @property
    def key(self) -> str:
        return ("E" if self.E else "e") + ("P" if self.P else "p") + ("h" if self.H == "compact" else "H") \
            + ("R" if self.R else "r") + ("C" if self.C else "c") + ("S" if self.S else "s") \
            + ("T" if self.S2 else "t") + ("U" if self.U else "u")


VARIANTS: dict[str, Switches] = {
    "V1": Switches(),                                                            # template v2.1 as frozen
    "V2": Switches(E=False),                                                     # v2.1 without experience lines
    "V3": Switches(P=False),                                                     # v2.1 without the physical description
    "V4": Switches(R=True),                                                      # v2.1 with relative context
    "V5": Switches(U=True),                                                      # v2.1 with the unanchored worker line
    "V6": Switches(S2=True, U=True),                                             # v2.1 with situation experience and U
    "V7": Switches(S2=True, U=True, R=True),                                     # ... and relative context
    "V8": Switches(H="compact", P=False, S2=True, U=True, R=True),               # compact, no physical, S', U, R
}
GRID_VARIANTS = ("V0", *VARIANTS)
NOTES = {
    "V0": "round-1 wording F1-R1 (the existing F1Policy; not a switch set)",
    "V1": "template v2.1 as frozen",
    "V2": "v2.1 without E (no experience lines)",
    "V3": "v2.1 without P (no physical description)",
    "V4": "v2.1 with R (relative context)",
    "V5": "v2.1 with U (unanchored worker choice)",
    "V6": "v2.1 with S' (situation experience) and U",
    "V7": "v2.1 with S', U and R",
    "V8": "compact history (H), without P, with S', U and R",
}


def sha256_file(path: Path | str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def definition_text(name: str, base_sha256: str) -> str:
    """The text of configs/policies/template_v2.2_r2/<name>.yaml (generated, so a test can compare the stored file)."""

    sw = VARIANTS[name]
    body = {
        "name": f"template_v2.2_{name}",
        "variant": name,
        "schema": SCHEMA,
        "base": "template_v2.1",
        "base_definition": BASE_DEFINITION,
        "base_definition_sha256": base_sha256,
        "switches": sw.as_json(),
        "switch_texts": "configs/prompts/template_v22/switch_texts.yaml",
        "situation_table": "configs/experience/situations_v22.json",
        "situation_rule": "leave one design out; one row per (design, brief, base state, worker, placement setting); a line needs "
                          "at least 3 other designs, else 'no evidence for this situation'; no design is named",
        "model": "gemini-3.1-flash-lite", "temperature": 0.3, "seeds": [0, 1, 2],
        "noise": "configs/noise_round2.yaml",
        "loop": "orch.episode_r2.run_episode_r2 with ROUND2 (both options on)",
        "wording_schema_truncation": "as template v2.1 (orch.policies.round2_harness TEXT_LIMITS); no power-specific wording",
        "note": NOTES[name],
    }
    header = (f"# Template v2.2 variant {name} (revision 2): {NOTES[name]}.\n"
              "# Independent switches on top of the frozen template v2.1 (orch/policies/v22_*.py). Nothing frozen is edited.\n")
    return header + yaml.safe_dump(body, sort_keys=False, width=120)


def load_variant(path: Path | str) -> tuple[str, Switches, dict[str, Any]]:
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError("not a template v2.2 (revision 2) variant file")
    sw = Switches(**{k: data["switches"][k] for k in SWITCH_NAMES})
    return data["variant"], sw, data


def load_switch_texts(project: Path | str) -> dict[str, Any]:
    return yaml.safe_load((Path(project) / "configs/prompts/template_v22/switch_texts.yaml").read_text(encoding="utf-8"))


def _when_matches(when: dict[str, Any], sw: Switches) -> bool:
    flags = {"E": sw.experience_shown, "P": sw.P, "H": sw.H, "R": sw.R, "C": sw.C, "S": sw.S, "S2": sw.S2, "U": sw.U}
    return all(flags[k] == v for k, v in when.items())


def apply_edits(text: str, edits: list[dict[str, Any]], sw: Switches, *, label: str) -> str:
    """Exact-once replacements for the switch settings that match; a miss or a repeat is an error."""

    for i, edit in enumerate(edits):
        if not _when_matches(edit["when"], sw):
            continue
        count = text.count(edit["old"])
        if count != 1:
            raise ValueError(f"{label} edit {i}: old text occurs {count} times")
        text = text.replace(edit["old"], edit["new"])
    return text


def template_text_for(base_text: str, sw: Switches, texts: dict[str, Any]) -> str:
    """The template v2.1 text with the edits for the switches that are off or on (unchanged for the defaults)."""

    return apply_edits(base_text, texts["template_edits"], sw, label="template")


def reply_texts_for(p4r_texts: dict[str, str], sw: Switches, texts: dict[str, Any]) -> dict[str, str]:
    out = dict(p4r_texts)
    for i, edit in enumerate(texts["reply_text_edits"]):
        if not _when_matches(edit["when"], sw):
            continue
        key = edit["key"]
        if out[key].count(edit["old"]) != 1:
            raise ValueError(f"reply text edit {i}: old text not found exactly once in {key}")
        out[key] = out[key].replace(edit["old"], edit["new"])
    return out
